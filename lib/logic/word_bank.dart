        .where((w) =>
            w.length >= 3 &&
            w.length <= maxLength &&
            !w.contains(' ') &&
            !w.contains('/'))
        .toList();
    list.shuffle();
    return list;
  }

  /// Category name for a given level (cycles through all 20 categories).
  static String categoryForLevel(int level) {
    return categoryNames[(level - 1) % categoryNames.length];
  }

  /// Display-friendly category name for a given level.
  static String categoryDisplayForLevel(int level) {
    final key = categoryForLevel(level);
    return categoryDisplayNames[key] ?? key;
  }
}
